'use strict';

/**
 * Auto-update over GitHub Releases.
 *
 * No file server of our own: `electron-updater` reads `latest.yml` from the
 * newest published GitHub release of this repository, downloads the NSIS
 * installer next to it, verifies the sha512 recorded in the manifest and then
 * hands it to the Windows installer.
 *
 * Design notes:
 *   - `autoDownload = false` on purpose: the user is asked before several tens
 *     of megabytes are pulled down on a possibly metered link.
 *   - Everything is silent on the automatic start-up check unless an update is
 *     actually available; failures only surface for a manual check.
 *   - State is pushed to the renderer (`deepcw:update-status`) so the About tab
 *     can show what is going on, and mirrored into a native dialog when the
 *     window is not focused.
 */

const { app, dialog, shell } = require('electron');

const OWNER = 'dedadeda26';
const REPO = 'deepcw-desktop';

/** @typedef {'idle'|'checking'|'available'|'downloading'|'downloaded'|'up-to-date'|'error'} UpdatePhase */

class UpdaterController {
  /**
   * @param {{ getWindow: () => import('electron').BrowserWindow | null,
   *           getLanguage: () => 'zh' | 'en' }} options
   */
  constructor(options) {
    this.getWindow = options.getWindow;
    this.getLanguage = options.getLanguage;
    /** @type {import('electron-updater').AppUpdater | null} */
    this.updater = null;
    /** @type {UpdatePhase} */
    this.phase = 'idle';
    this.currentVersion = app.getVersion();
    this.availableVersion = null;
    this.percent = 0;
    this.error = null;
    this.manualCheck = false;
    this.initialised = false;
  }

  get enabled() {
    return app.isPackaged && process.env.DEEPCW_NO_UPDATE !== '1';
  }

  status() {
    return {
      enabled: this.enabled,
      phase: this.phase,
      currentVersion: this.currentVersion,
      availableVersion: this.availableVersion,
      percent: this.percent,
      error: this.error,
    };
  }

  emit() {
    const win = this.getWindow();
    if (win && !win.isDestroyed()) {
      win.webContents.send('deepcw:update-status', this.status());
    }
  }

  setPhase(phase, patch = {}) {
    this.phase = phase;
    Object.assign(this, patch);
    if (process.env.DEEPCW_UPDATE_LOG === '1') {
      console.log(
        `[updater] ${phase}` +
          (this.availableVersion ? ` version=${this.availableVersion}` : '') +
          (this.error ? ` error=${this.error}` : '') +
          (this.percent ? ` percent=${this.percent}` : ''),
      );
    }
    this.emit();
  }

  t(zh, en) {
    return this.getLanguage() === 'zh' ? zh : en;
  }

  async init() {
    if (!this.enabled || this.initialised) return;
    this.initialised = true;

    let autoUpdater;
    try {
      ({ autoUpdater } = require('electron-updater'));
    } catch (error) {
      console.warn('[updater] electron-updater unavailable:', error.message);
      return;
    }
    this.updater = autoUpdater;
    autoUpdater.autoDownload = false;
    autoUpdater.autoInstallOnAppQuit = true;
    // Keep the download in %LOCALAPPDATA%; never touch the install directory
    // until the user confirms.
    autoUpdater.logger = null;

    // `app-update.yml` is generated by electron-builder from the `publish`
    // block. Fall back to an explicit feed so a locally built copy still works.
    try {
      autoUpdater.setFeedURL({ provider: 'github', owner: OWNER, repo: REPO });
    } catch (error) {
      console.warn('[updater] setFeedURL failed:', error.message);
    }

    autoUpdater.on('checking-for-update', () => {
      this.setPhase('checking', { error: null });
    });

    autoUpdater.on('update-available', (info) => {
      this.availableVersion = info?.version ?? null;
      this.setPhase('available');
      void this.promptDownload();
    });

    autoUpdater.on('update-not-available', () => {
      this.availableVersion = null;
      this.setPhase('up-to-date');
      if (this.manualCheck) {
        void dialog.showMessageBox({
          type: 'info',
          title: this.t('检查更新', 'Check for updates'),
          message: this.t(
            `已经是最新版本（${this.currentVersion}）。`,
            `You are up to date (${this.currentVersion}).`,
          ),
          buttons: [this.t('好', 'OK')],
        });
      }
      this.manualCheck = false;
    });

    autoUpdater.on('download-progress', (progress) => {
      this.percent = Math.max(0, Math.min(100, Math.round(progress?.percent ?? 0)));
      if (this.phase !== 'downloading') this.phase = 'downloading';
      this.emit();
    });

    autoUpdater.on('update-downloaded', (info) => {
      this.availableVersion = info?.version ?? this.availableVersion;
      this.percent = 100;
      this.setPhase('downloaded');
      void this.promptInstall();
    });

    autoUpdater.on('error', (error) => {
      this.error = error?.message ? String(error.message) : String(error);
      this.setPhase('error');
      if (this.manualCheck) {
        void dialog.showMessageBox({
          type: 'error',
          title: this.t('检查更新失败', 'Update check failed'),
          message: this.t(
            '无法连接 GitHub 检查更新。',
            'Could not reach GitHub to check for updates.',
          ),
          detail: this.error,
          buttons: [this.t('好', 'OK')],
        });
      }
      this.manualCheck = false;
    });
  }

  async promptDownload() {
    // Automated smoke tests: report the finding without blocking on a dialog.
    if (process.env.DEEPCW_UPDATE_NO_DIALOG === '1') {
      if (process.env.DEEPCW_UPDATE_AUTODOWNLOAD === '1') await this.download();
      return;
    }
    const version = this.availableVersion ?? '';
    const result = await dialog.showMessageBox({
      type: 'info',
      title: this.t('发现新版本', 'Update available'),
      message: this.t(
        `发现新版本 ${version}，当前 ${this.currentVersion}。`,
        `Version ${version} is available; you are on ${this.currentVersion}.`,
      ),
      detail: this.t(
        '现在下载吗？文件大约 110 MB，来自 GitHub Releases。下载完成后会提示重启安装。',
        'Download it now? About 110 MB from GitHub Releases. You will be asked to restart once it is downloaded.',
      ),
      buttons: [this.t('下载更新', 'Download'), this.t('以后再说', 'Later')],
      defaultId: 0,
      cancelId: 1,
    });
    if (result.response !== 0) {
      // Keep the banner ("有可用更新") but stop here.
      this.phase = 'available';
      this.emit();
      return;
    }
    await this.download();
  }

  async promptInstall() {
    const result = await dialog.showMessageBox({
      type: 'info',
      title: this.t('更新已就绪', 'Update ready'),
      message: this.t(
        `版本 ${this.availableVersion ?? ''} 已下载完成。`,
        `Version ${this.availableVersion ?? ''} has been downloaded.`,
      ),
      detail: this.t(
        '重启应用即可完成安装；选择“稍后”则会在退出时自动安装。',
        'Restart the app to install it now, or choose Later to install on exit.',
      ),
      buttons: [this.t('立即重启安装', 'Restart and install'), this.t('稍后', 'Later')],
      defaultId: 0,
      cancelId: 1,
    });
    if (result.response === 0) {
      this.install();
    }
  }

  async check({ manual = false } = {}) {
    await this.init();
    if (!this.enabled) {
      if (manual) {
        await dialog.showMessageBox({
          type: 'info',
          title: this.t('检查更新', 'Check for updates'),
          message: this.t(
            '当前是开发/未打包版本，自动更新只在安装版里生效。',
            'This build is not installed, so auto-update is disabled.',
          ),
          buttons: [this.t('好', 'OK')],
        });
      }
      return this.status();
    }
    if (this.phase === 'checking' || this.phase === 'downloading') {
      return this.status();
    }

    this.manualCheck = manual;
    this.error = null;
    this.setPhase('checking');
    try {
      await this.updater.checkForUpdates();
    } catch (error) {
      this.error = error?.message ? String(error.message) : String(error);
      this.setPhase('error');
      if (manual) {
        await dialog.showMessageBox({
          type: 'error',
          title: this.t('检查更新失败', 'Update check failed'),
          message: this.t(
            '无法连接 GitHub 检查更新。',
            'Could not reach GitHub to check for updates.',
          ),
          detail: this.error,
          buttons: [this.t('好', 'OK')],
        });
      }
      this.manualCheck = false;
    }
    return this.status();
  }

  async download() {
    await this.init();
    if (!this.enabled || !this.updater) return this.status();
    this.percent = 0;
    this.setPhase('downloading');
    try {
      await this.updater.downloadUpdate();
    } catch (error) {
      this.error = error?.message ? String(error.message) : String(error);
      this.setPhase('error');
    }
    return this.status();
  }

  install() {
    if (!this.updater || this.phase !== 'downloaded') return false;
    // isSilent=false so the NSIS UI (install dir, shortcuts) stays in charge.
    setImmediate(() => this.updater.quitAndInstall(false, true));
    return true;
  }

  /** Called once the window exists: silent check shortly after start-up. */
  scheduleStartupCheck(delayMs = 8000) {
    if (!this.enabled) return;
    const timer = setTimeout(() => {
      void this.check({ manual: false });
    }, delayMs);
    if (typeof timer.unref === 'function') timer.unref();
  }

  async openReleasePage() {
    await shell.openExternal(`https://github.com/${OWNER}/${REPO}/releases/latest`);
  }
}

let controller = null;

/** @param {{ getWindow: () => import('electron').BrowserWindow | null, getLanguage: () => 'zh' | 'en' }} options */
function initUpdater(options) {
  controller = new UpdaterController(options);
  return controller;
}

function getUpdater() {
  return controller;
}

module.exports = { initUpdater, getUpdater };
